#!/usr/bin/env python3
"""Generate React Native SVG building blocks from the brand kit (brand/svg).

Splits the BGYM mark into layers (ring back, athlete body, dumbbells, ring front, dot)
so the splash screen can animate each part, and exports the wordmark letters.
Run from the repo root:  python3 apps/mobile/scripts/generate-brand.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / 'brand' / 'svg'
OUT = ROOT / 'apps' / 'mobile' / 'src' / 'components' / 'brand' / 'generated.tsx'
NS = '{http://www.w3.org/2000/svg}'
TAGS = {'g': 'G', 'path': 'Path', 'rect': 'Rect', 'circle': 'Circle', 'ellipse': 'Ellipse', 'mask': 'Mask', 'defs': 'Defs'}
COLORS = {'#FFFFFF': '{ink}', '#FF5A1F': '{accent}'}


def camel(name: str) -> str:
    return re.sub(r'-([a-z])', lambda m: m.group(1).upper(), name)


def attr_value(key: str, value: str) -> str:
    if value in COLORS:
        return COLORS[value]
    m = re.fullmatch(r'url\(#(cut|gap)\d+\)', value)
    if m:
        return '{`url(#${id}-%s)`}' % m.group(1)
    if key == 'id':
        kind = re.sub(r'\d+$', '', value)
        return '{`${id}-%s`}' % kind
    return '"%s"' % value


def jsx(el: ET.Element, indent: int = 0) -> str:
    tag = TAGS[el.tag.replace(NS, '')]
    attrs = ' '.join(f'{camel(k)}={attr_value(k, v)}' for k, v in el.attrib.items())
    pad = '  ' * indent
    children = list(el)
    if not children:
        return f'{pad}<{tag} {attrs} />'.replace(' />', ' />')
    inner = '\n'.join(jsx(c, indent + 1) for c in children)
    return f'{pad}<{tag} {attrs}>\n{inner}\n{pad}</{tag}>'


mark = ET.parse(SRC / 'bgym-mark-on-dark.svg').getroot()
root_g = mark.find(f'{NS}g')
defs, ring_back, athlete, ring_front, dot = list(root_g)
bells, body = list(athlete)
assert bells.get('fill') == '#FF5A1F' and body.get('fill') == '#FFFFFF', 'unexpected mark structure'

word = ET.parse(SRC / 'bgym-wordmark-on-dark.svg').getroot()
letters = [(p.get('d'), p.get('fill') == '#FF5A1F') for p in word.findall(f'{NS}path')]

# Re-nest body inside the gap mask group (athlete minus dumbbells).
gap_group = ET.Element(athlete.tag, athlete.attrib)
gap_group.append(body)
body_jsx = '\n'.join([jsx(defs, 3), jsx(gap_group, 3)])
bells_jsx = jsx(bells, 3)

out = f'''// AUTO-GENERATED by apps/mobile/scripts/generate-brand.py from brand/svg. Do not edit by hand.
import {{ Circle, Defs, Ellipse, G, Mask, Path, Rect }} from 'react-native-svg';

export const MARK_VIEWBOX = '{mark.get('viewBox')}';
export const MARK_ORIGIN = '{root_g.get('transform')}';
export const MARK_ASPECT = {float(mark.get('width')) / float(mark.get('height')):.6f};

/** The orbit ellipse (in mark space) that the ring follows and the dot travels on. */
export const ORBIT = {{
  transform: '{ring_back.get('transform')}',
  backD: '{ring_back.get('d')}',
  frontD: '{ring_front.get('d')}',
  strokeWidth: {ring_back.get('stroke-width')},
  cx: 100,
  cy: 146,
  rx: 82,
  ry: 20,
  dotR: {dot.get('r')},
  /** Resting angle of the dot on the front of the orbit (radians). */
  restAngle: 0.78 * Math.PI,
}} as const;

export function MarkBody({{ ink, id }}: {{ ink: string; id: string }}) {{
  return (
    <G>
{body_jsx}
    </G>
  );
}}

export function MarkBells({{ accent }}: {{ accent: string }}) {{
  return (
{bells_jsx}
  );
}}

export const WORDMARK_VIEWBOX = '{word.get('viewBox')}';
export const WORDMARK_ASPECT = {float(word.get('width')) / float(word.get('height')):.6f};
export const WORDMARK_LETTERS: ReadonlyArray<{{ d: string; accent: boolean }}> = [
{chr(10).join(f"  {{ d: '{d}', accent: {'true' if a else 'false'} }}," for d, a in letters)}
];
'''
OUT.write_text(out)
print(f'Wrote {OUT.relative_to(ROOT)}')
